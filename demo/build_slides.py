doc = fitz.open()


def line(page, x1, y1, x2, y2, color=TEAL, width=2):
    page.draw_line((x1, y1), (x2, y2), color=color, width=width)


def rect(page, x, y, w, h, fill=PANEL, stroke=None, radius=0):
    shape = fitz.Rect(x, y, x + w, y + h)
    if radius:
        page.draw_rect(shape, color=stroke or fill, fill=fill, width=1, radius=radius)
    else:
        page.draw_rect(shape, color=stroke or fill, fill=fill, width=1)


def text(page, x, y, value, size=16, color=WHITE, bold=False):
    page.insert_text((x, y), value, fontsize=size, fontname="hebo" if bold else "helv", color=color)


def block(page, x, y, w, h, value, size=16, color=MUTED, bold=False):
    remaining = page.insert_textbox(
        fitz.Rect(x, y, x + w, y + h),
        value,
        fontsize=size,
        fontname="hebo" if bold else "helv",
        color=color,
        lineheight=1.2,
    )
    if remaining < -0.5:
        raise ValueError(f"Slide {len(doc)} text overflow: {value[:55]!r} ({remaining:.1f})")


def base(section, title, subtitle="", pending=True):
    page = doc.new_page(width=W, height=H)
    rect(page, 0, 0, W, H, BG)
    rect(page, 0, 0, 12, H, TEAL)
    text(page, 48, 42, "SIGNALDESK  /  DEVOPS CAPSTONE", 12, TEAL, True)
    text(page, 48, 94, title, 34, WHITE, True)
    if subtitle:
        block(page, 50, 107, 850, 44, subtitle, 15, MUTED)
    line(page, 48, 476, 912, 476, PANEL2, 1)
    text(page, 48, 501, section.upper(), 10, MUTED, True)
    text(page, 610, 501, "LIVE EVIDENCE PENDING" if pending else "LOCAL CHECKS VERIFIED", 10, AMBER if pending else TEAL, True)
    text(page, 884, 501, f"{len(doc):02d}", 10, MUTED, True)
    return page


def card(page, x, y, w, h, heading, body, accent=TEAL, body_size=15):
    rect(page, x, y, w, h, PANEL, PANEL2)
    rect(page, x, y, 5, h, accent)
    block(page, x + 18, y + 15, w - 32, 30, heading, 17, WHITE, True)
    block(page, x + 18, y + 55, w - 34, h - 67, body, body_size, MUTED)


def pill(page, x, y, w, label, fill=PANEL2, ink=TEAL):
    rect(page, x, y, w, 28, fill)
    text(page, x + 12, y + 19, label, 11, ink, True)


def arrow(page, x1, y, x2, color=TEAL):
    line(page, x1, y, x2 - 9, y, color, 2)
    line(page, x2 - 9, y, x2 - 17, y - 6, color, 2)
    line(page, x2 - 9, y, x2 - 17, y + 6, color, 2)


